#!/usr/bin/env python3
"""Generate the Rust table of per-column defaults, from the SQLAlchemy models.

`POST /api/import` writes only the columns a snapshot mentions — everything
else keeps whatever INSERT would have put there. For most columns that is the
DDL's DEFAULT clause, but several NOT NULL columns (e.g. `candidates.source`)
have their default in the ORM model, not in the schema. Without this table a
partial snapshot cannot be inserted at all: the port would have to bind NULL
and violate NOT NULL.

Values are emitted as SQL literals so they can be bound as-is.
"""

from app.infrastructure.database import Base
import app.models  # noqa: F401  — registers every model
import app.models.browser  # noqa: F401


def collect_rows() -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for table_name in sorted(Base.metadata.tables):
        table = Base.metadata.tables[table_name]
        for column in table.columns:
            default = column.default
            if default is None or default.is_server_default:
                continue
            argument = default.arg
            if callable(argument):
                # A Python callable (uuid4, now, ...) cannot be reproduced
                # here; the port generates those itself.
                continue
            if isinstance(argument, bool):
                literal = "1" if argument else "0"
            elif isinstance(argument, (int, float)):
                literal = str(argument)
            elif isinstance(argument, str):
                literal = "'" + argument.replace("'", "''") + "'"
            else:
                continue
            rows.append((table_name, column.name, literal))
    return rows


def main() -> int:
    rows = collect_rows()

    print("//! Static column defaults, generated from the SQLAlchemy models.")
    print("//!")
    print("//! `POST /api/import` writes only the columns a snapshot mentions, so a")
    print("//! missing NOT NULL column needs the value the ORM would have supplied.")
    print("//! Several of them (`candidates.source`, `positions.status`, …) have no")
    print("//! DEFAULT clause in the DDL, so SQLite alone cannot fill them.")
    print("//!")
    print("//! Generated by `scripts/gen_column_defaults.py`. Do not hand-edit.")
    print()
    print("/// `(table, column, SQL literal)`.")
    print(f"pub const COLUMN_DEFAULTS: &[(&str, &str, &str)] = &[")
    for table_name, column_name, literal in rows:
        print(f'    ("{table_name}", "{column_name}", "{literal}"),')
    print("];")
    print()
    print("/// The literal a column falls back to, if the model declares one.")
    print("pub fn column_default(table: &str, column: &str) -> Option<&'static str> {")
    print("    COLUMN_DEFAULTS")
    print("        .iter()")
    print("        .find(|(t, c, _)| *t == table && *c == column)")
    print("        .map(|(_, _, literal)| *literal)")
    print("}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
