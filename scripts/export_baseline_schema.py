#!/usr/bin/env python3
"""Export the baseline ICA SQLite schema as a create-able SQL snapshot.

Reads ``sqlite_master`` from the baseline database in read-only mode and
writes every table/index DDL verbatim (no reformatting) so the snapshot can
rebuild the schema in a throwaway database.

Usage:
    python3 scripts/export_baseline_schema.py \
        --db /mnt/o/ica/backend/ica.db \
        --out crates/ica-infra/schema/ica-baseline.sql

The script never opens the database read-write: the URI carries ``mode=ro``.
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

HEADER = """-- ICA baseline SQLite schema snapshot.
--
-- Generated by scripts/export_baseline_schema.py from
-- {db} (git HEAD d39e321) with `sqlite_master` read in mode=ro.
-- Do not hand-edit: regenerate with
--   python3 scripts/export_baseline_schema.py --db {db} --out {out}
--
-- Object count: {tables} tables, {indexes} indexes, {triggers} triggers,
-- {views} views. SQLite implicit auto-indexes (sql IS NULL) are skipped.
"""


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default="/mnt/o/ica/backend/ica.db")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    connection = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    rows = connection.execute(
        "SELECT type, name, tbl_name, sql FROM sqlite_master"
        " WHERE sql IS NOT NULL"
        " ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, rowid"
    ).fetchall()
    connection.close()

    counts = {"table": 0, "index": 0, "trigger": 0, "view": 0}
    statements: list[str] = []
    for kind, name, _table, sql in rows:
        counts[kind] = counts.get(kind, 0) + 1
        statements.append(f"-- {kind}: {name}\n{sql.strip()};\n")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = HEADER.format(
        db=args.db,
        out=args.out,
        tables=counts["table"],
        indexes=counts["index"],
        triggers=counts["trigger"],
        views=counts["view"],
    )
    text += "\n" + "\n".join(statements)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}: tables={counts['table']} indexes={counts['index']} "
          f"triggers={counts['trigger']} views={counts['view']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
