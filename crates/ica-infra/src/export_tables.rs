//! Table and column spec for `POST /api/export`.
//!
//! Generated from the SQLAlchemy models (`_BUSINESS_TABLES` +
//! `_EXPORT_COLUMN_EXCLUDES`) so the 195 columns cannot drift from the
//! baseline by a typo. Column ORDER matters: it is the order the JSON object
//! keys come out in, and the diff compares documents key-by-key.
//!
//! `import_sessions.raw_text` is absent on purpose — the baseline excludes it
//! from exports.

/// How a column's value must be rendered in JSON.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ColKind {
    Text,
    /// A SQLite TEXT holding `YYYY-MM-DD HH:MM:SS[.ffffff]`; rendered as
    /// `isoformat()` (`+00:00`, microseconds only when non-zero).
    DateTime,
    /// A SQLite INTEGER 0/1; rendered as JSON `true`/`false`.
    Bool,
    /// Rendered as a JSON integer.
    Int,
    /// Rendered as a JSON number with a fractional part.
    Float,
}

/// One exported table.
#[derive(Debug)]
pub struct TableSpec {
    pub name: &'static str,
    pub columns: &'static [(&'static str, ColKind)],
}

